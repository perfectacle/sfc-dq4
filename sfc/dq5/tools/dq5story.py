def bit(s):
    a, b = s.split('.')
    return int(a, 16), int(b)


def consumers(rom):
    """(바이트, 비트) → 그 비트를 보는 인물 목록·「인물 없음」·맵별 루틴·맵 조건 표."""
    out = defaultdict(list)
    for src, idx, val, kind, where, ctx in dq5flags.refs_lists(rom) + dq5flags.refs_hooks(rom) + dq5flags.refs_tables(rom):
        for b in dq5flags.bits_of(val):
            out[(dq5flags.FLAG_BASE + idx, b)].append(re.sub(r' \((켜짐|꺼짐)일 때\)', lambda m: '' if m.group(1) == '켜짐' else '(꺼짐)', where))
    return out


def setters(rom):
    out = defaultdict(list)
    refs = dq5flags.collect(rom, ['talk', 'npc', 'event', 'code', 'short'])
    for src, idx, val, kind, where, ctx in refs:
        if kind == 'set':
            for b in dq5flags.bits_of(val):
                out[(dq5flags.FLAG_BASE + idx, b)].append(where.split(' 06')[0])
    return out


def events_table(rom):
    use = consumers(rom)
    print('| 순서 | 단계 | 장소 | 사건 | 켜는 비트 | 거는 곳 | 바뀌는 인물·맵 | 근거 |')
    print('| --- | --- | --- | --- | --- | --- | --- | --- |')
    for n, (stage, place, what, bits, trigger, basis) in enumerate(EVENTS, 1):
        changed = []
        for s in bits.split():
            for c in use.get(bit(s), []):
                changed.append(f'{c} ← `{s}`')
        print(f'| {n} | {stage} | {place} | {what} | {" ".join(f"`{s}`" for s in bits.split()) or "-"} | {trigger} | '
              f'{"<br>".join(changed[:6]) + (f"<br>외 {len(changed) - 6}곳(아래 목록 표)" if len(changed) > 6 else "") or "-"} | {basis} |')


def lists_table(rom):
    """조건 비트 하나에 한 줄: 그 비트로 인물 목록이 바뀌거나 인물을 놓지 않는 맵들과 그 비트를 켜는 곳."""
    put = setters(rom)
    rows = defaultdict(lambda: ([], []))
    for src, idx, val, kind, where, ctx in dq5flags.refs_lists(rom):
        m = re.match(r'(인물 없음|인물 목록) (\w\w/\w\w)(?: → (\S+))? \((켜짐|꺼짐)일 때\)', where)
        for b in dq5flags.bits_of(val):
            lists, none = rows[(dq5flags.FLAG_BASE + idx, b, m.group(4))]
            (none if m.group(1) == '인물 없음' else lists).append(m.group(2) + (f'({m.group(3)})' if m.group(3) else ''))
    print('| 조건 | 목록이 바뀌는 맵(목록) | 인물을 놓지 않는 맵 | 그 비트를 켜는 곳 |')
    print('| --- | --- | --- | --- |')
    for (a, b, state), (lists, none) in sorted(rows.items()):
        by = sorted(set(put.get((a, b), [])))
        by = ', '.join(by[:3]) + (f' 외 {len(by) - 3}곳' if len(by) > 3 else '') if by else '없음'
        print(f'| `{a:04X}.{b}` {state} | {" ".join(lists) or "-"} | {" ".join(none) or "-"} | {by} |')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('rom')
    ap.add_argument('--lists', action='store_true')
    args = ap.parse_args()
    rom = Rom(open(args.rom, 'rb').read())
    if args.lists:
        lists_table(rom)
    else:
        events_table(rom)


if __name__ == '__main__':
    main()
