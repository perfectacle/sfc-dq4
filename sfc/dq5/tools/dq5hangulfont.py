"""한글 넣기 시제품용 글꼴. 자모를 선분·타원으로 직접 정의하고 글자 칸(예 11×13, 8×8)에 조합해 1bpp 점 그림을 만든다.

남의 글꼴 데이터를 쓰지 않으려고 자모 모양을 이 파일에 좌표로 적었다. 모양은 실현성 확인용이라 거칠다.
render(글자, 폭, 높이) -> 줄마다 0/1 목록.
"""

# 자모 획: ('l', x0, y0, x1, y1) 선분, ('o', cx, cy, rx, ry) 타원. 좌표는 자모 칸 안의 0~1.
CHO = {
    'ㄱ': [('l', 0, 0, 1, 0), ('l', 1, 0, 1, 1)],
    'ㄴ': [('l', 0, 0, 0, 1), ('l', 0, 1, 1, 1)],
    'ㄷ': [('l', 0, 0, 1, 0), ('l', 0, 0, 0, 1), ('l', 0, 1, 1, 1)],
    'ㄹ': [('l', 0, 0, 1, 0), ('l', 1, 0, 1, .5), ('l', 0, .5, 1, .5), ('l', 0, .5, 0, 1), ('l', 0, 1, 1, 1)],
    'ㅁ': [('l', 0, 0, 1, 0), ('l', 0, 0, 0, 1), ('l', 1, 0, 1, 1), ('l', 0, 1, 1, 1)],
    'ㅂ': [('l', 0, 0, 0, 1), ('l', 1, 0, 1, 1), ('l', 0, .5, 1, .5), ('l', 0, 1, 1, 1)],
    'ㅅ': [('l', .5, 0, 0, 1), ('l', .5, .2, 1, 1)],
    'ㅇ': [('o', .5, .5, .5, .5)],
    'ㅈ': [('l', 0, 0, 1, 0), ('l', .5, 0, 0, 1), ('l', .5, .2, 1, 1)],
    'ㅊ': [('l', .5, -.2, .5, 0), ('l', 0, .1, 1, .1), ('l', .5, .1, 0, 1), ('l', .5, .3, 1, 1)],
    'ㅎ': [('l', .5, -.1, .5, .1), ('l', 0, .2, 1, .2), ('o', .5, .65, .4, .35)],
}
# 중성: (세로 부분 획, 가로 부분 획). 세로 모음은 글자 오른쪽, 가로 모음은 아래에 놓는다.
JUNG = {
    'ㅏ': ([('l', .4, 0, .4, 1), ('l', .4, .5, 1, .5)], None),
    'ㅐ': ([('l', .3, 0, .3, 1), ('l', .3, .5, .7, .5), ('l', .9, 0, .9, 1)], None),
    'ㅑ': ([('l', .4, 0, .4, 1), ('l', .4, .35, 1, .35), ('l', .4, .65, 1, .65)], None),
    'ㅓ': ([('l', .7, 0, .7, 1), ('l', 0, .5, .7, .5)], None),
    'ㅔ': ([('l', .5, 0, .5, 1), ('l', 0, .5, .5, .5), ('l', 1, 0, 1, 1)], None),
    'ㅕ': ([('l', .7, 0, .7, 1), ('l', 0, .35, .7, .35), ('l', 0, .65, .7, .65)], None),
    'ㅣ': ([('l', .5, 0, .5, 1)], None),
    'ㅗ': (None, [('l', 0, 1, 1, 1), ('l', .5, .3, .5, 1)]),
    'ㅛ': (None, [('l', 0, 1, 1, 1), ('l', .3, .3, .3, 1), ('l', .7, .3, .7, 1)]),
    'ㅜ': (None, [('l', 0, 0, 1, 0), ('l', .5, 0, .5, .8)]),
    'ㅠ': (None, [('l', 0, 0, 1, 0), ('l', .3, 0, .3, .8), ('l', .7, 0, .7, .8)]),
    'ㅡ': (None, [('l', 0, .5, 1, .5)]),
    'ㅚ': ([('l', .6, 0, .6, 1)], [('l', 0, 1, 1, 1), ('l', .5, .3, .5, 1)]),
    'ㅘ': ([('l', .4, 0, .4, 1), ('l', .4, .5, 1, .5)], [('l', 0, 1, 1, 1), ('l', .5, .3, .5, 1)]),
}
JONG = {k: v for k, v in CHO.items()}
CHO_ORDER = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
JUNG_ORDER = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
JONG_ORDER = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'


def decompose(ch):
    c = ord(ch) - 0xAC00
    return CHO_ORDER[c // 588], JUNG_ORDER[c % 588 // 28], JONG_ORDER[c % 28].strip()


def _draw(grid, strokes, box):
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0

    def put(x, y):
        x, y = int(round(x)), int(round(y))
        if 0 <= y < len(grid) and 0 <= x < len(grid[0]):
            grid[y][x] = 1
    for s in strokes:
        if s[0] == 'l':
            ax, ay, bx, by = x0 + s[1] * w, y0 + s[2] * h, x0 + s[3] * w, y0 + s[4] * h
            n = int(max(abs(bx - ax), abs(by - ay))) + 1
            for i in range(n + 1):
                t = i / n
                put(ax + (bx - ax) * t, ay + (by - ay) * t)
        else:
            import math
            cx, cy, rx, ry = x0 + s[1] * w, y0 + s[2] * h, s[3] * w, s[4] * h
            for i in range(64):
                a = i * math.pi / 32
                put(cx + rx * math.cos(a), cy + ry * math.sin(a))


def render(ch, w, h):
    """글자 ch 를 w×h 칸에 그린 줄 목록(1 = 점). 한글이 아니면 빈 칸."""
    grid = [[0] * w for _ in range(h)]
    if not '가' <= ch <= '힣':
        return grid
    cho, jung, jong = decompose(ch)
    vert, horiz = JUNG[jung]
    W, H = w - 1, h - 1
    top = H * (0.55 if jong else 1.0)
    if vert and not horiz:
        _draw(grid, CHO[cho], (0, 0.5, W * 0.55, top - 0.5))
        _draw(grid, vert, (W * 0.6, 0, W, top))
    elif horiz and not vert:
        _draw(grid, CHO[cho], (W * 0.15, 0, W * 0.85, top * 0.5))
        _draw(grid, horiz, (0, top * 0.65, W, top))
    else:
        _draw(grid, CHO[cho], (0, 0, W * 0.5, top * 0.45))
        _draw(grid, horiz, (0, top * 0.55, W * 0.6, top))
        _draw(grid, vert, (W * 0.6, 0, W, top))
    if jong:
        _draw(grid, JONG[jong], (W * 0.15, top + 1, W * 0.85, H))
    return grid
