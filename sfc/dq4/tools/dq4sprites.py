def _palette(colors: dict[str, tuple[int, int, int]]) -> list[int]:
    """5비트 채널 색을 MesenCE 와 같은 8비트(v<<3|v>>2)로 편 768바이트 팔레트."""
    flat = [0, 0, 0]
    for key in "123456789ABCDEF":
        rgb = colors.get(key, (0, 0, 0))
        flat.extend((v << 3) | (v >> 2) for v in rgb)
    return flat


