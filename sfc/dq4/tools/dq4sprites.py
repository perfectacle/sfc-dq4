def _rows(text: str) -> list[str]:
    rows = [line for line in text.strip("\n").split("\n") if line]
    for row in rows:
        if len(row) != WIDTH:
            raise ValueError(f"row width {len(row)} != {WIDTH}: {row!r}")
    return rows


def _image(rows: list[str], palette: list[int]) -> Image.Image:
    if len(rows) != HEIGHT:
        raise ValueError(f"{len(rows)} rows, expected {HEIGHT}")
    im = Image.new("P", (WIDTH, HEIGHT), 0)
    im.putpalette(palette)
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            if char != ".":
                im.putpixel((x, y), int(char, 16))
    im.info["transparency"] = 0
    return im


def _step(rows: list[str], side: bool) -> list[str]:
    """정지 자세에서 보행 자세를 만든다. 머리(0~15)는 그대로 두고 몸만 바꾼다.

    정면·후면은 몸의 명암을 좌우로 뒤집어 흔들림을 주고 발 줄을 한 픽셀 당긴다.
    측면은 발 줄을 두 픽셀 뒤로 보낸다. DQ5 가 머리를 고정하고 몸 두 장을 번갈아 쓰는 것과 같다.
    """
    head, body = rows[:HEAD_ROWS], rows[HEAD_ROWS:]
    if side:
        body = body[:5] + [".." + body[5][:-2]] + body[6:]
    else:
        body = [row[::-1] for row in body[:5]] + [body[5][1:] + "."] + body[6:]
    return head + body


def _frames(name: str) -> dict[str, list[str]]:
    spec = MATRICES[name]
    out = {}
    for view in ("front", "left", "back"):
        rows = _rows(spec[view])
        out[view] = rows
        if f"{view}_b" in spec:
            alt = _rows(spec[f"{view}_b"])
            out[f"{view}_b"] = alt if len(alt) == HEIGHT else rows[:HEAD_ROWS] + alt
        else:
            out[f"{view}_b"] = _step(rows, side=view == "left")
    return out


def build_sheet(name: str) -> Image.Image:
    """48×96 시트: 행은 남·서·동·북, 열은 정지·보행·정지(DQ5 처럼 두 자세를 번갈아 씀)."""
    palette = _palette(PALETTES[name])
    f = _frames(name)
    front = [_image(f["front"], palette), _image(f["front_b"], palette)]
    left = [_image(f["left"], palette), _image(f["left_b"], palette)]
    right = [im.transpose(Image.Transpose.FLIP_LEFT_RIGHT) for im in left]
    back = [_image(f["back"], palette), _image(f["back_b"], palette)]
    sheet = Image.new("P", (WIDTH * 3, HEIGHT * 4), 0)
    sheet.putpalette(palette)
    for r, pair in enumerate((front, left, right, back)):
        for c, im in enumerate((pair[0], pair[1], pair[0])):
            sheet.paste(im, (c * WIDTH, r * HEIGHT))
    sheet.info["transparency"] = 0
    return sheet


SPRITE_NAMES = tuple(MATRICES)


def build_sprites() -> dict[str, Image.Image]:
    return {name: build_sheet(name) for name in SPRITE_NAMES}


