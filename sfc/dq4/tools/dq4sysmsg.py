TOKEN = re.compile(r'\{([A-Z]|은|이|을|로|과)\}|…|[^{…]+')


def parts(line):
    """한 줄을 (부분 목록, 너비)로."""
    out, width = [], 0
    for m in TOKEN.finditer(line):
        tok, key = m.group(0), m.group(1)
        if key in SLOTS:
            code, w = SLOTS[key]
            out.append(code)
            width += w
        elif key in JOSA:
            out.append(JOSA[key])
            width += 2 if key == '로' else 1     # 「으로」 는 두 칸
        elif tok == '…':
            out.append(DOTS)
            width += 1
        else:
            out.append(tok)
            width += len(tok)
    return out, width


def message(text, end=END):
    out = [NARR]
    lines = text.split('/')
    if len(lines) > 4:
        raise ValueError(f'4줄을 넘음: {text}')
    for n, line in enumerate(lines):
        p, w = parts(line)
        if w > LINE_COLS:
            raise ValueError(f'한 줄에 안 들어감({w}칸): {line}')
        if n:
            out.append(LINE)
        out += p
    return out + [end]


