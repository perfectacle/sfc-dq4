TOKEN = re.compile(r'\{([A-Z]|은|이여|이|을|로|과|아)\}|…|[^{…]+')


def parts(line):
    """한 줄을 (부분 목록, 너비)로."""
    out, width = [], 0
    for m in TOKEN.finditer(line):
        tok, key = m.group(0), m.group(1)
        if key in SLOTS:
            code, w = SLOTS[key]
            out.append(code)
            width += w
        elif key in JOSA:
            out.append(JOSA[key])
            width += JOSA_COLS.get(key, 1)
        elif tok == '…':
            out.append(DOTS)
            width += 1
        else:
            out.append(tok)
            width += len(tok)
    return out, width


def message(text, end=END, narrate=True):
    """서술은 쪽마다 {1006} 으로 연다(쪽을 넘기면 첫 코드를 다시 봄, dq4chapter1.narrate)."""
    out = []
    for k, page in enumerate(text.split('|')):
        lines = dq4wrap.wrap(page, lambda s: parts(s)[1], NARR_COLS if narrate else LINE_COLS)
        if len(lines) > PAGE_LINES:
            raise ValueError(f'{PAGE_LINES}줄을 넘음: {page}')
        if k:
            out.append(PAGE)
        if narrate:
            out.append(NARR)
        for n, line in enumerate(lines):
            p, _ = parts(line)
            if n:
                out.append(LINE)
            out += p
    return out + [end]


def _end(m):
    return END_WAIT if m in WAIT else END


